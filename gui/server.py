#: Where `npm run build` (gui/frontend/) outputs the production bundle —
#: exposed at module level (not just a local inside create_app()) so
#: gui_app.py (Epic M4's desktop entry point) can check it exists and give
#: a clear message before ever opening a window against a backend with no
#: UI mounted.
STATIC_DIR = Path(__file__).resolve().parent / "static"


def create_app(settings: Settings | None = None) -> FastAPI:
    """`settings` is injectable so tests can pass a Settings pointed at
    tmp_path sandboxes (same pattern as tests/test_bootstrap.py) instead
    of requiring a real .env/API key — `uvicorn gui.server:app` (the real
    entry point, see the module-level `app` below) always uses the real
    load_settings()."""

    @asynccontextmanager
    async def _lifespan(app: FastAPI) -> AsyncIterator[None]:
        resolved_settings = settings if settings is not None else load_settings()
        sink = WebSocketSink()
        session_store = ChatSessionStore(resolved_settings.chat_sessions_dir)
        session_sink = SessionSink(session_store)
        logger = AuraLogger([JSONLSink(resolved_settings.logs_dir), sink, session_sink])
        confirmation_channel = WebSocketConfirmationChannel(sink, logger)
        app.state.ctx = await build_app_context(resolved_settings, confirmation_channel, logger)
        app.state.sink = sink
        app.state.session_store = session_store
        app.state.session_sink = session_sink
        # search_project_chats needs a ChatSessionStore -- a GUI-only
        # concept build_app_context() never sees (see
        # tools/projects/project_tool.py's module docstring) -- so it's
        # registered here, after both it and ctx exist, rather than
        # inside build_app_context() like the other three project tools.
        # orchestrator's capabilities (config/agents.json) already lists
        # its name, so no leader_view widening is needed once it exists.
        register_project_chat_search_tool(
            app.state.ctx.registry,
            app.state.ctx.active_project,
            session_store,
            lambda: session_sink.active_session_id,
            app.state.ctx.agent_registry.leader.name,
        )
        # Skills staged via POST /api/skills/stage but not yet committed
        # (Epic M3) -- in-memory only, keyed by a uuid; same "small,
        # process-lifetime pending state" shape as ws_channel.py's
        # pending-Futures dict, just for a two-step HTTP flow instead of a
        # WebSocket round trip.
        app.state.staged_skills = {}
        try:
            yield
        finally:
            await app.state.ctx.aclose()

    app = FastAPI(title="AuraAgent GUI backend", lifespan=_lifespan)
    app.include_router(api_router, dependencies=[Depends(require_device_token)])
    app.include_router(sync_router, dependencies=[Depends(require_device_token)])
    app.include_router(graph_router, dependencies=[Depends(require_device_token)])

    @app.websocket("/ws")
    async def websocket_endpoint(websocket: WebSocket) -> None:
        # Checked BEFORE accept() (N14) -- an unauthorized socket is never
        # opened at all, not accepted-then-closed. No-op (always True) when
        # settings.require_auth is off, which is the default -- see
        # gui/auth.py.
        ctx: AppContext = websocket.app.state.ctx
        if not await check_ws_token(websocket, ctx.device_store, ctx.settings.require_auth):
            return
        await websocket.accept()
        sink: WebSocketSink = websocket.app.state.sink
        session_store: ChatSessionStore = websocket.app.state.session_store
        session_sink: SessionSink = websocket.app.state.session_sink
        # ctx.confirmation_channel is a SwappableConfirmationChannel (see
        # confirmation/swappable_channel.py) -- .current is the real
        # WebSocketConfirmationChannel this method needs .resolve() on.
        # Safe to grab once here rather than re-reading .current on every
        # message: a scheduled run can only ever swap it away while
        # holding ctx.run_lock, which a live turn on THIS connection also
        # holds for its own entire duration (see main.py/_run_orchestrator's
        # own `async with ctx.run_lock:`), so it can never be swapped out
        # from under an in-flight confirmation round trip.
        confirmation_channel = ctx.confirmation_channel.current
        assert isinstance(confirmation_channel, WebSocketConfirmationChannel)
        leader_name = ctx.agent_registry.leader.name

        # Own queue for this connection alone (N14) -- see gui/ws_log_sink.py's
        # module docstring for why a shared queue across connections isn't safe.
        connection_id = str(uuid4())
        sink.register(connection_id)
        drain_task = asyncio.create_task(sink.drain(connection_id, websocket))
        # Tracks in-flight orchestrator runs so they can be cancelled if
        # the connection drops, and so asyncio doesn't warn about a task
        # result never being retrieved (see _run_orchestrator's own
        # try/except for the "surface errors instead of losing them" half).
        # Also doubles as the busy flag guarding `history` below: non-empty
        # means a run is in flight on this connection right now.
        run_tasks: set[asyncio.Task[None]] = set()

        # Resume the most-recently-updated saved session, or start a fresh
        # one if this is the very first connection ever -- "open AuraAgent,
        # see your last conversation" (see module docstring). `history` is
        # reconstructed from that session's own persisted events, NOT
        # stored separately -- see service.history_from_events(). Under run_lock
        # (N14): this sets the shared active_session_id/sink.current
        # pointers and mutates ctx's shared workspace_root/active_project
        # state, same as a turn does -- must not interleave with another
        # connection doing the same or with a turn in flight.
        async with ctx.run_lock:
            existing = await session_store.list_sessions()
            active_session = existing[0] if existing else await session_store.create_session()
            session_sink.active_session_id = active_session.id
            sink.current = connection_id
            active_events = session_store.read_events(active_session.id)
            history: list[ConversationTurn] = service.history_from_events(active_events, leader_name)
            await _sync_active_directory(ctx, active_session, sink, leader_name)
            sink.write(_session_loaded_event(active_session, active_events))

        try:
            while True:
                raw = await websocket.receive_text()
                message = json.loads(raw)
                msg_type = message.get("type")
                if msg_type == "user_message":
                    if run_tasks:
                        ctx.logger.log_error(
                            -1,
                            "Ignored: a previous message is still being processed on this connection.",
                            agent_name=leader_name,
                        )
                        continue
                    # This connection's OWN active session, never read back
                    # from the shared session_sink.active_session_id
                    # pointer -- by the time this task actually runs (or
                    # even by the time it's scheduled, if another
                    # connection's action slips in first), that pointer may
                    # already belong to a different connection (N14).
                    session_id = active_session.id
                    task = asyncio.create_task(
                        _run_orchestrator(
                            ctx, message["text"], history, session_store, sink, session_sink, connection_id, session_id
                        )
                    )
                    run_tasks.add(task)
                    task.add_done_callback(run_tasks.discard)
                elif msg_type == "confirmation_response":
                    confirmation_channel.resolve(message["request_id"], message["approved"])
                elif msg_type == "open_question_response":
                    confirmation_channel.resolve(message["request_id"], message["answer"])
                elif msg_type == "new_chat":
                    # Sidebar "New chat": a brand-new saved session, not
                    # just a cleared display -- guarded by the same busy
                    # check as user_message so it can't race a run in flight.
                    # Tagged to the Project named in the message (the
                    # Project detail view's own "+ New chat"), else to
                    # whichever Project is currently active, if any -- a
                    # new chat started while "inside" a Project belongs to
                    # it automatically, no manual tagging step needed.
                    if run_tasks:
                        ctx.logger.log_error(
                            -1,
                            "Ignored: wait for the current turn to finish before starting a new chat.",
                            agent_name=leader_name,
                        )
                    else:
                        async with ctx.run_lock:
                            project_slug = message.get("project_slug") or ctx.active_project.current_slug
                            active_session = await session_store.create_session(project_slug=project_slug)
                            session_sink.active_session_id = active_session.id
                            sink.current = connection_id
                            history = []
                            await _sync_active_directory(ctx, active_session, sink, leader_name)
                            sink.write(_session_loaded_event(active_session, []))
                elif msg_type == "set_active_session":
                    # Sidebar: switch to a previously-saved session (its
                    # list comes from GET /api/sessions). Reconstructs
                    # `history` from that session's own persisted events so
                    # the Leader actually continues it, not just re-displays it.
                    if run_tasks:
                        ctx.logger.log_error(
                            -1,
                            "Ignored: wait for the current turn to finish before switching chats.",
                            agent_name=leader_name,
                        )
                    else:
                        target = await session_store.get_session(message["session_id"])
                        if target is None:
                            ctx.logger.log_error(
                                -1, f"No such chat session '{message['session_id']}'.", agent_name=leader_name
                            )
                        else:
                            async with ctx.run_lock:
                                active_session = target
                                session_sink.active_session_id = target.id
                                sink.current = connection_id
                                target_events = session_store.read_events(target.id)
                                history = service.history_from_events(target_events, leader_name)
                                await _sync_active_directory(ctx, target, sink, leader_name)
                                sink.write(_session_loaded_event(target, target_events))
                elif msg_type == "quick_note_sync":
                    accepted = _append_quick_notes(ctx, message.get("items", []))
                    # Re-assert (N14): `await websocket.receive_text()` above
                    # is a real yield point another connection's own action
                    # could run during, same reasoning as every other
                    # sink.current assignment in this handler.
                    sink.current = connection_id
                    sink.write(
                        {
                            "ts": datetime.now(timezone.utc).isoformat(),
                            "event_type": "quick_note_sync_ack",
                            "payload": {"accepted_client_ids": accepted},
                        }
                    )
                elif msg_type == "hello":
                    catchup = await _build_sync_catchup(ctx, message.get("last_synced_at"))
                    sink.current = connection_id
                    sink.write(
                        {
                            "ts": datetime.now(timezone.utc).isoformat(),
                            "event_type": "sync_catchup",
                            "payload": catchup,
                        }
                    )
                # An unrecognized message type is silently ignored rather
                # than closing the connection — matches main.py's REPL,
                # which tolerates a blank/malformed line without crashing
                # the whole session over it.
        except WebSocketDisconnect:
            pass
        finally:
            drain_task.cancel()
            sink.unregister(connection_id)
            for task in run_tasks:
                task.cancel()

    if STATIC_DIR.is_dir():
        app.mount("/", StaticFiles(directory=STATIC_DIR, html=True), name="static")

    return app




async def _sync_active_directory(
    ctx: AppContext, session: SessionInfo, sink: WebSocketSink, leader_name: str
) -> None:
    """Keeps the active Project/directory in lockstep with whichever chat
    just became active (see module docstring) -- delegates entirely to
    cli/service.py::sync_active_directory(). _run_orchestrator() below
    calls that same shared function again, unconditionally, right before
    every single turn; this call here just makes the switch visible
    immediately (e.g. in the Leader's system prompt) without waiting for
    the human to send a message first. Swallows a stale Project reference
    (the chat was tagged to a Project that has since been deleted) rather
    than blocking the chat switch over it; the chat itself keeps its
    now-dangling tag, same as ProjectStore never cascading a delete onto
    anything that referenced it."""
    try:
        await service.sync_active_directory(
            ctx.cli_context, project_slug=session.project_slug, directory_override=session.directory
        )
    except ValueError as exc:
        ctx.logger.log_error(-1, f"Could not switch to this chat's project: {exc}", agent_name=leader_name)


def _session_loaded_event(info: SessionInfo, events: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "ts": datetime.now(timezone.utc).isoformat(),
        "event_type": "session_loaded",
        "payload": {"id": info.id, "title": info.title, "events": events},
    }


async def _run_orchestrator(
    ctx: AppContext,
    text: str,
    history: list[ConversationTurn],
    session_store: ChatSessionStore,
    sink: WebSocketSink,
    session_sink: SessionSink,
    connection_id: str,
    session_id: str,
) -> None:
    is_first_exchange = not history
    try:
        # Shared with tools/scheduler/scheduler_loop.py's own runs -- see
        # main.py's matching `async with ctx.run_lock:` for why.
        async with ctx.run_lock:
            # Re-assert the routing pointers (N14) -- another connection's
            # own action (a chat switch, its own turn) may have repointed
            # sink.current/session_sink.active_session_id to itself while
            # this task was merely scheduled, waiting its turn for
            # run_lock. Every event this turn produces from here on must
            # land on THIS connection's queue and THIS session's file.
            sink.current = connection_id
            session_sink.active_session_id = session_id
            # Defensive re-sync: the chat-switch-time sync above (module
            # docstring) already set the right directory when this chat
            # became active, but re-resolving it again here, right before
            # the turn actually runs, means this turn is correct
            # regardless of whatever happened in between (a scheduled
            # task, a directory change from another connection) -- see
            # cli/service.py::sync_active_directory()'s own docstring.
            # Cheap no-op when nothing has actually changed.
            session = await session_store.get_session(session_id)
            if session is not None:
                try:
                    await service.sync_active_directory(
                        ctx.cli_context, project_slug=session.project_slug, directory_override=session.directory
                    )
                except ValueError as exc:
                    ctx.logger.log_error(-1, f"Could not resolve this chat's directory: {exc}")
            answer = await ctx.orchestrator.run(text, history=history)
    except Exception as exc:  # noqa: BLE001 - surface to the GUI's event stream, mirroring main.py's REPL
        ctx.logger.log_error(-1, f"{type(exc).__name__}: {exc}")
        return
    await session_store.touch(session_id)
    if is_first_exchange:
        await _maybe_autoname_session(ctx, session_store, sink, connection_id, session_id, text, answer)


async def _maybe_autoname_session(
    ctx: AppContext,
    session_store: ChatSessionStore,
    sink: WebSocketSink,
    connection_id: str,
    session_id: str,
    user_text: str,
    answer_text: str,
) -> None:
    """Best-effort: a title generated from the first exchange is a nice
    touch, not something the actual chat turn should ever fail over. Only
    fires if the title is still the default placeholder -- a session
    renamed manually (e.g. right after creation, before sending anything)
    is left alone."""
    info = await session_store.get_session(session_id)
    if info is None or info.title != DEFAULT_TITLE:
        return
    try:
        response = await ctx.provider.send(
            "Generate a short, specific title (3-6 words, no quotes, no trailing punctuation) for a chat "
            "that starts with this exchange. Reply with ONLY the title text, nothing else.",
            [ConversationTurn(role="user", text=f"User: {user_text}\n\nAssistant: {answer_text}")],
            [],
        )
        title = (response.thought_text or "").strip().strip('"').strip("'").strip()
    except Exception:  # noqa: BLE001 - see docstring: auto-naming never breaks the actual chat turn
        return
    if not title:
        return
    try:
        updated = await session_store.rename_session(session_id, title)
    except ValueError:
        return
    # Best-effort re-assert (N14): this runs after run_lock was already
    # released (see _run_orchestrator), so another connection's action
    # could in principle repoint sink.current first -- low-stakes if it
    # does (the rename itself, above, is already correctly persisted by
    # session_id regardless; only this live notification could then reach
    # the wrong tab), so this isn't itself wrapped in another lock.
    sink.current = connection_id
    sink.write(
        {
            "ts": datetime.now(timezone.utc).isoformat(),
            "event_type": "session_renamed",
            "payload": {"id": updated.id, "title": updated.title},
        }
    )


def _append_quick_notes(ctx: AppContext, items: list[dict[str, Any]]) -> list[str]:
    """Routes each item into ITS OWN day's daily note file (by
    captured_at's date, not necessarily "today" -- a phone syncing an
    offline backlog may span several days), under
    `ctx.cli_context.quick_notes_subdir` (default "Daily Notes",
    configurable via /notes quickdir -- see cli/service.py), formatted as
    one Thino-style bullet: `- HH:MM:SS <text verbatim>`, no tag
    parsing/rewriting -- whatever the phone sent (with or without an
    inline #tag, wherever positioned) is passed straight through. This is
    a deterministic, no-judgment-call operation, so it's done directly
    here rather than through the LLM/ToolRegistry layer -- see
    tools/notes/thino_format.py for the shared formatting logic also used
    by the LLM-facing save_quick_note tool (same module). Returns the
    client_ids actually written, for the quick_note_sync_ack reply."""
    accepted: list[str] = []
    for item in items:
        text = item.get("text")
        client_id = item.get("client_id")
        if not text or not client_id:
            continue
        when = parse_captured_at(item.get("captured_at"))
        daily_note_path = resolve_within_sandbox(
            ctx.cli_context.notes_root.current,
            f"{ctx.cli_context.quick_notes_subdir}/{when.strftime('%Y-%m-%d')} 日记.md",
        )
        insert_thino_line(daily_note_path, f"- {when.strftime('%H:%M:%S')} {text}")
        accepted.append(client_id)
    return accepted


async def _build_sync_catchup(ctx: AppContext, last_synced_at: str | None) -> dict[str, Any]:
    """N14 (Auralis / remote access): answers a reconnecting client's
    "hello" by bundling what it missed into ONE reply, instead of making
    it separately poll GET /api/schedules etc. itself. `last_synced_at`
    is the client's own last-successful-sync timestamp (ISO string, or
    None/missing if it has never synced before -- in which case every
    schedule with a recorded run is included, not just recent ones).

    Known limitation, deliberately not solved here: `ScheduleStore` only
    ever keeps the LATEST result per schedule (see
    tools/scheduler/schedule_store.py), not a full run history -- a
    recurring schedule that fired several times while the client was
    offline is reported with just its most recent result, not each
    individual run. Good enough for "what did I miss," not a complete
    audit log.

    Does NOT include a catch-up for a confirmation_request a disconnected
    client left unanswered -- gui/server.py's websocket_endpoint cancels
    that turn entirely on disconnect (see its own `finally` block), so
    there is nothing pending left to resume by the time a client
    reconnects; the human has to re-ask."""
    since: datetime | None = None
    if last_synced_at:
        try:
            since = datetime.fromisoformat(last_synced_at.replace("Z", "+00:00"))
        except ValueError:
            since = None

    schedules = await ctx.schedule_store.list_schedules()
    schedule_results = []
    for schedule in schedules:
        if not schedule.last_run_at:
            continue
        ran_at = datetime.fromisoformat(schedule.last_run_at)
        if since is not None:
            compare_since = since.replace(tzinfo=None) if since.tzinfo else since
            if ran_at <= compare_since:
                continue
        schedule_results.append(
            {
                "schedule_id": schedule.id,
                "task": schedule.task,
                "summary": schedule.last_result_summary,
                "ran_at": schedule.last_run_at,
            }
        )

    project_status = await service.get_project_status(ctx.cli_context)
    active_project = None
    if project_status.active_slug is not None:
        active_project = next(
            (p for p in project_status.projects if p.slug == project_status.active_slug), None
        )

    return {
        "schedule_results": schedule_results,
        "active_project": (
            {"slug": active_project.slug, "name": active_project.name} if active_project is not None else None
        ),
    }


