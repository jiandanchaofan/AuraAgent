"""FastAPI backend for the AuraAgent GUI.

Calls the exact same core/bootstrap.py::build_app_context() the CLI
(main.py) does, swapping in a WebSocketConfirmationChannel + WebSocketSink
instead of TerminalConfirmationChannel + TerminalSink — everything else
(the tool registry, the team, all six self-extension tools) is identical.
This is the architectural guarantee behind "CLI and GUI stay feature-equal"
(see core/bootstrap.py's module docstring).

M1 scope (this module): a single shared AppContext for the whole process's
lifetime — one shared backend, matching main.py's own single-process model.
Multiple SIMULTANEOUS connections (the desktop GUI plus a connected
Auralis phone, or two browser tabs) ARE supported (N14): each gets its own
WebSocketSink queue (keyed by a per-connection `connection_id`, see
gui/ws_log_sink.py) so one connection's events can never be delivered to a
different one's socket, and its own `active_session` local, so switching
chats on one connection never touches another's. What is NOT supported is
two connections' turns actually running at the same instant —
`ctx.run_lock` (held for the full duration of a turn, and for any other
action that touches the shared workspace_root/active_project/Leader state:
the initial connect-time sync, "new_chat", "set_active_session") still
serializes ALL of that, GUI and CLI and the scheduler alike, exactly as
before. A second connection's message just waits for the lock like
everything else always has; it is never corrupted by what the first
connection is doing. Chat *sessions* (below) are a different thing from
connections: many sessions can be saved, and now more than one CAN be live
across different connections at once, each on its own connection's own
`active_session`.

Auth (N14): when `settings.require_auth` is on (see gui/auth.py and
config/settings.py's AURA_REQUIRE_AUTH — off by default, so a purely local
setup is unaffected), every REST route requires a valid device Bearer
token (tools/devices/device_store.py) and `/ws` requires one as a `?token=`
query param, checked BEFORE accept() so an unauthorized socket is never
even opened. This is what makes it safe to put this process behind a
Cloudflare Tunnel for a real Auralis phone to reach.

Sessions (persistence across restarts, tools/sessions/session_store.py):
each connection has an "active session" — SessionSink (gui/session_sink.py)
appends every event into that session's own file as it happens, so a
conversation survives a server restart and can be resumed later, not just
within one connection's lifetime the way Epic N1's `history` alone would
be. On connect, the most-recently-updated session is resumed automatically
(or a fresh one is created if none exist yet) — "open AuraAgent, see your
last conversation" is the whole point. `history` (the actual per-connection
conversation memory the Leader engine reads) is reconstructed from a
session's persisted top-level user_input/final_answer events, not stored
as a second, redundant representation — see `cli/service.py::history_from_events()`
(shared with telegram_bot.py, the Telegram frontend -- moved there so neither
frontend duplicates this reconstruction logic).
Deliberately simplified versus the engine's real internal `history` (which
also carries raw provider tool-call turns, per AsyncReActEngine's own
docstring): resuming a session gives the model back the conversational
gist (what was asked, what was answered), not an exact tool-call replay.
This is the same tradeoff essentially every consumer chat product makes,
and keeps a saved session provider-agnostic (switching LLM provider between
sessions never corrupts one).

A session's title is auto-generated by a lightweight, tool-free LLM call
after its first exchange (see `_maybe_autoname_session`) if it's still the
default placeholder — this never blocks or fails the actual chat turn (see
that function's own try/except). A human can always override it via the
sidebar's rename control (PATCH /api/sessions/{id}, gui/routes.py) — the
one shared `ChatSessionStore.rename_session()` path handles both.

Project/directory <-> Chat sync (see `_sync_active_directory`): a chat can
optionally belong to a Project (`SessionInfo.project_slug`) and/or carry
its own working directory (`SessionInfo.directory`, only actually used
while it has no Project tag -- a Project always outranks it). Whenever a
chat becomes the active one on this connection (initial connect,
"new_chat", "set_active_session"), `cli/service.py::sync_active_directory()`
re-resolves which directory/Project actually governs it -- now always
under `ctx.run_lock` (N14), since this mutates the same shared
workspace_root/active_project/Leader state a turn does, and two
connections doing this "at the same time" (e.g. one switches chats while
another's turn is mid-flight) must not interleave. `_run_orchestrator()`
calls the exact same function again, right before every single turn,
also inside `ctx.run_lock` -- not just relying on the chat-switch sync
above, so a turn's directory can never be left stale by whatever ran in
between (a scheduled task, another connection). See that function's own
docstring for the full priority chain and the bug this replaced
(workspace_root used to be a single global value /workspace set and
/project use would silently clobber back and forth).

Per-connection routing (N14): `sink.current` and `session_sink
.active_session_id` both say "route the next event to THIS one" --
exactly like `ctx.workspace_root`/`ctx.active_project`, these are shared,
process-wide pointers, so every place that sets them (the three spots
above, plus `_run_orchestrator`) does so only while holding `ctx.run_lock`,
for the same reason. Each connection also keeps its own `active_session`
local (never read back from `session_sink.active_session_id`, which could
have moved on to a different connection by the time it's read) -- this is
what `user_message` sends into `_run_orchestrator` as `session_id`, not
the shared pointer.

M2 adds the actual frontend (gui/frontend/, a minimal React+Vite app) —
`npm run build` there outputs straight into gui/static/, which this module
mounts and serves at "/" whenever that directory exists, so a single
`uvicorn gui.server:app` serves both the WebSocket API and the built UI.
If gui/static/ hasn't been built yet (e.g. in tests, or before running
`npm run build`), "/" simply isn't mounted and /ws still works fine on its
own — that's how M1 was exercised before any frontend existed, with a raw
WebSocket client/script.

Wire protocol (JSON messages):
  Server -> client: every AuraLogger event (user_input/calling_llm/
    thought/tool_call/observation/confirmation/final_answer/error — see
    core/logger.py), PLUS confirmation_request / open_question_request
    (from ConfirmationChannel, see gui/ws_channel.py), PLUS session_loaded
    (payload: {id, title, events}, sent right after connecting and after
    new_chat/set_active_session), session_renamed (payload: {id, title}),
    quick_note_sync_ack (payload: {accepted_client_ids: [...]}), and
    sync_catchup (payload: {schedule_results: [...], active_project:
    {slug, name} | null} — see _build_sync_catchup, sent in reply to a
    client's own "hello") — all share the same {event_type, payload, ...}
    shape on one ordered stream, routed to the ONE connection that caused
    them (gui/ws_log_sink.py's `current` pointer). PLUS schedule_result
    (payload: {schedule_id, task, summary} — see
    tools/scheduler/scheduler_loop.py), the one event type that's
    BROADCAST to every connected device instead of routed to one (a
    finished background task isn't "this connection's" event the way
    everything else here is).
  Client -> server: {"type": "user_message", "text": "..."} to run the
    orchestrator; {"type": "confirmation_response", "request_id": ...,
    "approved": true|false}; {"type": "open_question_response",
    "request_id": ..., "answer": "..."}; {"type": "new_chat",
    "project_slug": "..." (optional)} to start a brand-new saved session,
    tagged to that Project if given, else to whichever Project is currently
    active (if any); {"type": "set_active_session", "session_id": "..."}
    to switch to an existing one (its list comes from GET /api/sessions,
    gui/routes.py); {"type": "quick_note_sync", "items": [{"client_id":
    ..., "text": ..., "captured_at": ...}]} -- a phone's offline-captured
    quick notes, each appended as a Thino-style bullet into ITS OWN day's
    daily note file (see _append_quick_notes) once connectivity resumes;
    {"type": "hello", "last_synced_at": "..." (optional ISO timestamp)} --
    sent once right after connecting (N14, e.g. by a reconnecting Auralis
    phone) to request a sync_catchup reply bundling what it missed, instead
    of it separately polling several REST endpoints itself.

IMPORTANT concurrency note: handling "user_message" must NEVER block this
handler's `while True: await websocket.receive_text()` loop. orchestrator
.run() can itself block inside a ConfirmationChannel.confirm() call,
waiting for a "confirmation_response" message — and that message can only
ever arrive by this SAME loop reaching receive_text() again. Running the
orchestrator inline here would deadlock: the run() that's waiting for a
response would itself be what's preventing that response from ever being
read. So "user_message" is dispatched as a background asyncio.Task, never
awaited directly in the receive loop.

Epic N1 gives each connection a persistent `history` list, passed into
every `ctx.orchestrator.run(text, history=history)` call so the Leader
actually remembers earlier turns within one connection. Because
"user_message" runs as a background Task rather than being awaited inline,
a SECOND "user_message" arriving while the first is still running would
race on that same mutable list — so "user_message" (and "new_chat"/
"set_active_session", which reassign `history` outright) are rejected
whenever `run_tasks` already shows a run in flight; the frontend already
disables its input while busy, this is just the server-side enforcement.
"""
